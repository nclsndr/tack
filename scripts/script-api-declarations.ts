#!/usr/bin/env bun
// Writes the script API's declarations into the CLI, which `tack types` and the package build turn
// into a source's editor stub. A test fails until the shipped module matches; run
// `bun run script-api:types` after changing `packages/core/src/script-api.ts`.
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const checkout = join(import.meta.dirname, "..");

/** The declarations `tsc` emits for the script API, with internal names stripped. */
export const emitScriptApiDeclarations = (): string => {
  const output = mkdtempSync(join(tmpdir(), "tack-script-api-"));
  const emitted = spawnSync(
    join(checkout, "node_modules/.bin/tsc"),
    [
      "--ignoreConfig",
      "--declaration",
      "--emitDeclarationOnly",
      "--stripInternal",
      "--strict",
      "--skipLibCheck",
      "--target",
      "es2022",
      "--module",
      "nodenext",
      "--outDir",
      output,
      join(checkout, "packages/core/src/script-api.ts"),
    ],
    { cwd: checkout, encoding: "utf8" },
  );
  if (emitted.status !== 0) throw new Error(`Declaration emit failed: ${emitted.stdout}`);
  return readFileSync(join(output, "script-api.d.ts"), "utf8");
};

if (import.meta.main) {
  const target = join(checkout, "apps/cli/src/domain/execution/script-api-declarations.ts");
  writeFileSync(
    target,
    [
      "// Generated by `bun run script-api:types` from packages/core/src/script-api.ts. Do not edit.",
      "",
      "/** The script API's declarations, as `tsc` emits them with internal names stripped. */",
      `export const scriptApiDeclarations = ${JSON.stringify(emitScriptApiDeclarations())};`,
      "",
    ].join("\n"),
  );
  console.log(`Wrote ${target}`);
}
