import { expect, it } from "@effect/vitest";
import { Effect, FileSystem, Path } from "effect";
import { LiveTestLayer } from "../../../test/support/live-test-layer.ts";
import { emitScriptApiDeclarations } from "../../../../../scripts/script-api-declarations.ts";
import { scriptApiDeclarations } from "../../domain/execution/script-api-declarations.ts";
import {
  generatedTsconfig,
  TypesTargetError,
  tsconfigCovers,
  typesStub,
  writeTypes,
} from "./script-types.ts";

it("ships the script API declarations that tsc emits from the API", () => {
  // Run `bun run script-api:types` after changing packages/core/src/script-api.ts.
  expect(scriptApiDeclarations).toBe(emitScriptApiDeclarations());
}, 60_000);

it("wraps the declarations in an ambient module under the published name, with the version", () => {
  const stub = typesStub("1.2.3");
  expect(stub.split("\n")[0]).toBe(
    "// Generated by Tack 1.2.3: the script API that Tack provides at run time. Scripts import",
  );
  expect(stub).toContain('declare module "@tackup/cli" {');
  expect(stub).toContain("  export function defineScript<");
  expect(stub).not.toMatch(/^\s+(export )?declare /m);
  expect(stub).not.toContain("recognizeScript");
  expect(stub.endsWith("}\n")).toBe(true);
});

it("reads whether a tsconfig.json includes the stub", () => {
  expect(tsconfigCovers("{}")).toBe(true);
  expect(tsconfigCovers(generatedTsconfig)).toBe(true);
  expect(tsconfigCovers('{"include": ["**/*"]}')).toBe(true);
  expect(tsconfigCovers('{"include": ["./*.d.ts"]}')).toBe(true);
  expect(tsconfigCovers('{"files": ["./tack-env.d.ts"]}')).toBe(true);
  expect(tsconfigCovers('{"include": ["scripts/**/*.ts"]}')).toBe(false);
  expect(tsconfigCovers('{"files": ["scripts/run.ts"]}')).toBe(false);
  expect(tsconfigCovers("{ // comment\n}")).toBeUndefined();
  expect(tsconfigCovers('{"include": "scripts"}')).toBeUndefined();
});

it.layer(LiveTestLayer)("tack types", (test) => {
  const source = Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const root = yield* fs.realPath(yield* fs.makeTempDirectoryScoped({ prefix: "tack-types-" }));
    yield* fs.writeFileString(path.join(root, "tack.yaml"), "version: 1\n");
    return { fs, path, root };
  });

  test.effect("previews, then writes the stub and a tsconfig.json, then finds them current", () =>
    Effect.gen(function* () {
      const { fs, path, root } = yield* source;
      const stub = path.join(root, "tack-env.d.ts");
      const tsconfig = path.join(root, "tsconfig.json");

      const preview = yield* writeTypes(root, "1.0.0", false);
      expect(preview).toEqual({
        directory: root,
        files: [
          { path: stub, action: "create" },
          { path: tsconfig, action: "create" },
        ],
        inScope: true,
      });
      expect(yield* fs.exists(stub)).toBe(false);

      yield* writeTypes(root, "1.0.0", true);
      expect(yield* fs.readFileString(stub)).toBe(typesStub("1.0.0"));
      expect(yield* fs.readFileString(tsconfig)).toBe(generatedTsconfig);

      expect((yield* writeTypes(root, "1.0.0", true)).files.map(({ action }) => action)).toEqual([
        "unchanged",
        "keep",
      ]);
      const upgraded = yield* writeTypes(root, "2.0.0", true);
      expect(upgraded.files[0]?.action).toBe("update");
      expect(yield* fs.readFileString(stub)).toBe(typesStub("2.0.0"));
    }),
  );

  test.effect("keeps an existing tsconfig.json and says whether it includes the stub", () =>
    Effect.gen(function* () {
      const { fs, path, root } = yield* source;
      const own = '{"include": ["scripts/**/*.ts"]}\n';
      yield* fs.writeFileString(path.join(root, "tsconfig.json"), own);

      const plan = yield* writeTypes(root, "1.0.0", true);
      expect(plan.inScope).toBe(false);
      expect(yield* fs.readFileString(path.join(root, "tsconfig.json"))).toBe(own);
    }),
  );

  test.effect("refuses a folder without tack.yaml", () =>
    Effect.gen(function* () {
      const { fs, path, root } = yield* source;
      const other = path.join(root, "other");
      yield* fs.makeDirectory(other);

      const error = yield* Effect.flip(writeTypes(other, "1.0.0", true));
      expect(error).toEqual(new TypesTargetError({ directory: other }));
      expect(yield* fs.exists(path.join(other, "tack-env.d.ts"))).toBe(false);
    }),
  );
});
