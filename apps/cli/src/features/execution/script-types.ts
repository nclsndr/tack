import picomatch from "picomatch";
import { Effect, FileSystem, Path, Schema } from "effect";
import { publishedPackageName } from "../../domain/execution/published-name.ts";
import { scriptApiDeclarations } from "../../domain/execution/script-api-declarations.ts";

/** The editor stub's file name, at the root of a source. */
export const typesStubName = "tack-env.d.ts";

/**
 * The editor stub for the script API: its declarations as an ambient module under the published
 * name, which the running Tack provides, so a source's editor knows the import without an install.
 */
export const typesStub = (version: string): string =>
  [
    `// Generated by Tack ${version}: the script API that Tack provides at run time. Scripts import`,
    `// "${publishedPackageName}" and install nothing. Run \`tack types --apply\` again after upgrading Tack.`,
    `declare module "${publishedPackageName}" {`,
    // Inside `declare module`, declarations are already ambient and take no `declare` keyword.
    scriptApiDeclarations
      .replace(/^(export )?declare /gm, "$1")
      .trimEnd()
      .replace(/^(?=.)/gm, "  "),
    "}",
    "",
  ].join("\n");

/**
 * The `tsconfig.json` written when a source has none. Without one, an editor never loads the stub.
 * Bundler resolution matches what the worker accepts: extensionless and `.ts` relative imports.
 */
export const generatedTsconfig = `${JSON.stringify(
  {
    compilerOptions: {
      target: "es2022",
      module: "preserve",
      moduleResolution: "bundler",
      allowImportingTsExtensions: true,
      resolveJsonModule: true,
      strict: true,
      noEmit: true,
      skipLibCheck: true,
    },
    include: ["**/*.ts", typesStubName],
  },
  null,
  2,
)}\n`;

/** What `tack types` does, or did, to one file. */
type TypesFileAction = "create" | "update" | "unchanged" | "keep";

/** The `types` plan: the source folder, each file's action, and whether the stub is in scope. */
export type TypesPlan = {
  readonly directory: string;
  readonly files: ReadonlyArray<{ readonly path: string; readonly action: TypesFileAction }>;
  /**
   * Whether the source's `tsconfig.json` includes the stub; `null` when Tack cannot read it, so the
   * author checks it by hand.
   */
  readonly inScope: boolean | null;
};

/** A folder that is not a source root: `tack types` writes only next to a `tack.yaml`. */
export class TypesTargetError extends Schema.TaggedError<TypesTargetError>()("TypesTargetError", {
  directory: Schema.String,
}) {}

const TsconfigScopeSchema = Schema.Struct({
  include: Schema.optionalKey(Schema.Array(Schema.String)),
  files: Schema.optionalKey(Schema.Array(Schema.String)),
});

/**
 * Whether a `tsconfig.json` text includes the stub at its root: TypeScript includes every file when
 * the config lists neither `include` nor `files`. A config Tack cannot parse, such as one with
 * comments, gives `undefined`.
 */
export const tsconfigCovers = (text: string): boolean | undefined => {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch {
    return undefined;
  }
  const scope = Schema.decodeUnknownOption(TsconfigScopeSchema)(parsed);
  if (scope._tag === "None") return undefined;
  const { include, files } = scope.value;
  if (include === undefined && files === undefined) return true;
  return (
    (files ?? []).some((file) => file.replace(/^\.\//, "") === typesStubName) ||
    (include ?? []).some((pattern) =>
      picomatch.isMatch(typesStubName, pattern.replace(/^\.\//, ""), { dot: true }),
    )
  );
};

/**
 * Plans, and with `apply` writes, the editor stub and a `tsconfig.json` in one source folder. An
 * existing `tsconfig.json` is never changed; the plan says whether it includes the stub.
 */
export const writeTypes = Effect.fn("execution.writeTypes")(function* (
  directory: string,
  version: string,
  apply: boolean,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const root = path.resolve(directory);
  if ((yield* fs.exists(path.join(root, "tack.yaml"))) === false)
    return yield* new TypesTargetError({ directory: root });
  const stubPath = path.join(root, typesStubName);
  const stub = typesStub(version);
  const current = (yield* fs.exists(stubPath)) ? yield* fs.readFileString(stubPath) : undefined;
  const stubAction: TypesFileAction =
    current === undefined ? "create" : current === stub ? "unchanged" : "update";
  const tsconfigPath = path.join(root, "tsconfig.json");
  const tsconfig = (yield* fs.exists(tsconfigPath))
    ? yield* fs.readFileString(tsconfigPath)
    : undefined;
  if (apply === true) {
    if (stubAction !== "unchanged") yield* fs.writeFileString(stubPath, stub);
    if (tsconfig === undefined) yield* fs.writeFileString(tsconfigPath, generatedTsconfig);
  }
  return {
    directory: root,
    files: [
      { path: stubPath, action: stubAction },
      { path: tsconfigPath, action: tsconfig === undefined ? "create" : "keep" },
    ],
    inScope: tsconfig === undefined ? true : (tsconfigCovers(tsconfig) ?? null),
  } satisfies TypesPlan;
});
