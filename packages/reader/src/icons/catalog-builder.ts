import { readdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** What the icon catalog needs from an installed Lucide: its version, names and old names. */
export type LucidePackage = {
  readonly version: string;
  readonly icons: readonly { readonly name: string; readonly aliases: readonly string[] }[];
};

/** The directory of lucide-react's per-icon ES modules, one file per name and per old name. */
export function lucideIconsDirectory(): string {
  return join(dirname(fileURLToPath(import.meta.resolve("lucide-react"))), "../esm/icons");
}

/** Reads the installed lucide-react: every icon module's name and aliases, and the version. */
export async function readLucidePackage(): Promise<LucidePackage> {
  const directory = lucideIconsDirectory();
  const manifest: unknown = JSON.parse(
    await readFile(join(directory, "../../../package.json"), "utf8"),
  );
  const version =
    typeof manifest === "object" &&
    manifest !== null &&
    "version" in manifest &&
    typeof manifest.version === "string"
      ? manifest.version
      : "";
  const files = (await readdir(directory)).filter((file) => file.endsWith(".mjs"));
  const modules = await Promise.all(
    files.map(async (file) => readFile(join(directory, file), "utf8")),
  );
  const icons = modules.flatMap((source) => {
    const name = /^ {2}name: "([^"]+)",$/m.exec(source)?.[1];
    if (name === undefined) return [];
    const aliases = /^ {2}aliases: \[([^\]]*)\]/m.exec(source)?.[1] ?? "";
    return [
      { name, aliases: [...aliases.matchAll(/"([^"]+)"/g)].flatMap(([, alias]) => alias ?? []) },
    ];
  });
  return { version, icons: icons.toSorted((left, right) => left.name.localeCompare(right.name)) };
}

const list = (names: readonly string[]) =>
  `[${names.map((name) => JSON.stringify(name)).join(", ")}]`;

/**
 * The source of `catalog.generated.ts`: the curated names by category, the old Lucide names of
 * curated icons, and every other Lucide name, all from one installed version.
 *
 * @throws An error listing every curated name that is renamed, missing or listed twice.
 */
export function iconCatalogSource(
  curated: Readonly<Record<string, readonly string[]>>,
  lucide: LucidePackage,
): string {
  const canonical = new Map(lucide.icons.map((icon) => [icon.name, icon]));
  const renamed = new Map(
    lucide.icons.flatMap((icon) => icon.aliases.map((alias) => [alias, icon.name] as const)),
  );
  const names = Object.values(curated).flat();
  const problems = names.flatMap((name, index) => {
    if (names.indexOf(name) !== index) return [`- "${name}" is listed twice`];
    if (canonical.has(name)) return [];
    const current = renamed.get(name);
    return [
      current === undefined
        ? `- "${name}" is not a Lucide icon`
        : `- "${name}" is now "${current}"`,
    ];
  });
  if (problems.length > 0)
    throw new Error(
      [`The curated icons do not match lucide-react ${lucide.version}:`, ...problems].join("\n"),
    );
  const curatedSet = new Set(names);
  const aliases = names.flatMap(
    (name) =>
      canonical.get(name)?.aliases.map((alias) => `${JSON.stringify(alias)}: "${name}"`) ?? [],
  );
  const others = lucide.icons
    .filter((icon) => !curatedSet.has(icon.name))
    .flatMap((icon) => [icon.name, ...icon.aliases])
    .toSorted();
  return [
    `// Generated by \`bun run icons:catalog\` from src/icons/curated.ts and lucide-react ${lucide.version}.`,
    "// Do not edit: a test fails until this file matches them.",
    "",
    "/** The lucide-react version the docs icon set was checked against. */",
    `export const lucideVersion = ${JSON.stringify(lucide.version)};`,
    "",
    "/** The icons docs may use, by category. */",
    "export const docsIconCategories = [",
    ...Object.entries(curated).map(
      ([category, members]) =>
        `  { category: ${JSON.stringify(category)}, names: ${list(members)} },`,
    ),
    "] as const;",
    "",
    "/** Old Lucide names of icons in the docs set, to their current name. */",
    `export const docsIconAliases = { ${aliases.join(", ")} } as const;`,
    "",
    "/** Every other Lucide name and old name in this version: icons outside the docs set. */",
    `export const otherLucideNames = ${JSON.stringify(others.join(" "))};`,
    "",
  ].join("\n");
}
