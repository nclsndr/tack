/**
 * Writes `cli-imports.ts`: the folder-level import graph of `apps/cli/src`, as the links of the
 * Tack CLI architecture map. Run it from anywhere with `bun packages/reader/fixtures/figures/cli-import-graph.ts`.
 *
 * Each id is the folder path with "/" replaced by "-"; a file directly under `services/` is its own
 * box. The two bootstrap files share the id "bootstrap". Left out: imports from or to a root file
 * (main.ts, release.ts, version.ts), imports between two domain folders, tests and built-ins.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../../../apps/cli/src");
const output = join(import.meta.dirname, "cli-imports.ts");

const files = (directory: string): readonly string[] =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory() === true) return entry.name === "builtins" ? [] : files(path);
    return entry.name.endsWith(".ts") === true && entry.name.endsWith(".test.ts") === false
      ? [path]
      : [];
  });

/** The box a source file belongs to, or `undefined` for a root file. */
const boxOf = (file: string): string | undefined => {
  const parts = relative(root, file).split("/");
  const [tier, second] = parts;
  if (parts.length === 1 || tier === undefined || second === undefined) return undefined;
  if (tier === "bootstrap") return "bootstrap";
  return `${tier}-${second.replace(/\.ts$/, "")}`;
};

const tierOf = (box: string): string => box.split("-")[0] ?? box;

const labelOf = (from: string, to: string): string | undefined => {
  if (tierOf(from) === "platform" && tierOf(to) === "services") return "implements";
  if (from === "bootstrap" && tierOf(to) === "platform") return "wires";
  return undefined;
};

const edges = [
  ...new Set(
    files(root).flatMap((file) => {
      const from = boxOf(file);
      if (from === undefined) return [];
      return [
        ...readFileSync(file, "utf8").matchAll(/(?:from\s+|\bimport\(\s*)["'](\.[^"']+)["']/g),
      ]
        .map((match) => boxOf(resolve(dirname(file), match[1] ?? "")))
        .flatMap((to) =>
          to === undefined || to === from || (tierOf(from) === "domain" && tierOf(to) === "domain")
            ? []
            : [`${from} ${to}`],
        );
    }),
  ),
].toSorted();

const lines = edges.map((edge) => {
  const [from = "", to = ""] = edge.split(" ");
  const label = labelOf(from, to);
  return `  { from: "${from}", to: "${to}"${label === undefined ? "" : `, label: "${label}"`} },`;
});

writeFileSync(
  output,
  [
    "// Generated by cli-import-graph.ts from apps/cli/src. Do not edit by hand: run the script again.",
    "//",
    '// Each id is the folder path with "/" replaced by "-". Left out: root files, imports between two',
    '// domain folders, tests and built-ins. "implements": a platform adapter imports its port.',
    '// "wires": bootstrap imports a platform adapter.',
    "",
    `/** The ${edges.length} folder-level imports of the Tack CLI: \`from\` imports \`to\`. */`,
    "export const links = [",
    ...lines,
    "];",
    "",
  ].join("\n"),
);
console.log(`${edges.length} links written to ${relative(process.cwd(), output)}`);
